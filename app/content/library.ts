const ME_KEY = "reach-me";
export function readMe(): Me | null { try { const v = JSON.parse(localStorage.getItem(ME_KEY) || "null"); return v && v.who ? v : null; } catch { return null; } }
export function saveMe(m: Me | null) { try { if (m) localStorage.setItem(ME_KEY, JSON.stringify(m)); else localStorage.removeItem(ME_KEY); } catch { /* private window */ } }

/* does this item fit this person? */
export function fits(i: LibItem, who: Who, stage?: string, groups: string[] = []) {
  if (!i.who.includes(who)) return false;
  if (stage && !i.stages.includes(stage)) return false;
  if (i.groups.length && !i.groups.some((g) => groups.includes(g))) return false;
  return true;
}
export const madeFor = (i: LibItem, groups: string[]) => i.groups.length > 0 && i.groups.some((g) => groups.includes(g));

export function track(key: string) { rpc("eff_reach_item_click", { p_key: key }).catch(() => {}); }
export function report(key: string, reason: string, note?: string) { return rpc("eff_reach_item_flag", { p_key: key, p_reason: reason, p_note: note || null }); }
